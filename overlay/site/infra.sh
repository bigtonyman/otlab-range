#!/bin/sh
# Site OT infrastructure host: DNS, NTP server and syslog collector, all in the foreground of one container.
# Generic across scenarios; the site is set by the environment:
#   SITE_DOMAIN      DNS domain to serve and append     (e.g. tkfarm.lan)
#   SITE_HOSTS       addn-hosts file inside the image   (default /opt/site/hosts, mounted by the scenario)
#   SITE_NTP_ALLOW   space-separated subnets chrony serves time to (e.g. "10.213.40.0/24 192.168.0.0/24")
set -eu
DOMAIN=${SITE_DOMAIN:?SITE_DOMAIN not set}
HOSTS=${SITE_HOSTS:-/opt/site/hosts}
mkdir -p /var/log/remote /var/lib/chrony

# chrony: serve the VM's clock (-x, never steps it), stratum 8, to the site subnets. Built from env so the
# image carries no site addresses.
{ echo "# generated by infra.sh from SITE_NTP_ALLOW"
  echo "local stratum 8"
  for net in ${SITE_NTP_ALLOW:-}; do echo "allow $net"; done
  echo "driftfile /var/lib/chrony/drift"
} > /etc/chrony/chrony.conf

# chronyd serves UDP 123 off the VM clock (-x, never steps it). It daemonizes (forks), so clear any stale pidfile
# first - on a container restart a leftover /run/chrony/chronyd.pid makes it refuse to start ("Another chronyd may
# already be running"). With -d (debug/foreground) this alpine build instead exits at once when it has no sources,
# so daemonize rather than run -d. -r lets it reload without complaint if a prior instance's state remains.
rm -f /run/chrony/chronyd.pid
chronyd -x -f /etc/chrony/chrony.conf

# dnsmasq and rsyslogd stay in the foreground; wait on them so the container lives as long as they do.
dnsmasq --keep-in-foreground --no-resolv --no-hosts --addn-hosts="$HOSTS" --expand-hosts --domain="$DOMAIN" \
        --local=/"$DOMAIN"/ --log-queries --log-facility=/var/log/dnsmasq.log &
# Same stale-pidfile trap as chronyd: after a container restart rsyslogd refuses to start (error -3000) and the
# collector silently stays empty. Clear it first.
rm -f /var/run/rsyslogd.pid
rsyslogd -n -f /opt/site/rsyslog.conf &
wait
